const reversePhrases = Object.fromEntries(Object.entries(phrases).map(([sr, en]) => [en, sr]));
const dateWords: Record<string, string> = {
  ponedeljak: "Monday", utorak: "Tuesday", sreda: "Wednesday", četvrtak: "Thursday", petak: "Friday", subota: "Saturday", nedelja: "Sunday",
  pon: "Mon", uto: "Tue", sre: "Wed", čet: "Thu", pet: "Fri", sub: "Sat", ned: "Sun",
  januar: "January", februar: "February", mart: "March", april: "April", maj: "May", jun: "June", jul: "July", avgust: "August", septembar: "September", oktobar: "October", novembar: "November", decembar: "December",
  jan: "Jan", feb: "Feb", avg: "Aug", sep: "Sep", okt: "Oct", nov: "Nov", dec: "Dec",
};
const reverseDateWords = Object.fromEntries(Object.entries(dateWords).map(([sr, en]) => [en.toLowerCase(), sr]));
const dynamicTerms: Record<Locale, Record<string, string>> = {
  sr: {
    owner: "Vlasnik", admin: "Administrator", staff: "Zaposleni", notified: "Obavešten/a", waiting: "Čeka",
  },
  en: {
    owner: "Owner", admin: "Administrator", staff: "Staff", notified: "Notified", waiting: "Waiting",
  },
};

function translateDateWords(text: string, locale: Locale) {
  if (!/\d{1,2}[.,]/.test(text)) return text;
  const dictionary = locale === "en" ? dateWords : reverseDateWords;
  return text.replace(/\p{L}+/gu, (word) => {
    const replacement = dictionary[word.toLocaleLowerCase("sr-Latn")];
    if (!replacement) return word;
    return word[0] === word[0].toLocaleUpperCase("sr-Latn")
      ? replacement[0].toLocaleUpperCase("en") + replacement.slice(1)
      : replacement;
  });
}

export function translateDocument(locale: Locale) {
  if (typeof document === "undefined" || !document.body) return () => {};
  const dictionary = locale === "en" ? phrases : reversePhrases;

  function translateText(node: Node) {
    if (node.parentElement?.closest("[data-no-translate]")) return;
    const text = node.nodeValue ?? "";
    const trimmed = text.trim();
    if (!trimmed) return;

    const translated = dynamicTerms[locale][trimmed] ?? dictionary[trimmed] ?? translateDateWords(trimmed, locale);
    if (translated && translated !== trimmed) node.nodeValue = text.replace(trimmed, translated);
  }

  function translateAttributes(element: Element) {
    if (element.closest("[data-no-translate]")) return;
    for (const attribute of ["aria-label", "placeholder", "title", "alt"]) {
      const value = element.getAttribute(attribute);
      const translated = value && dictionary[value];
      if (translated && translated !== value) element.setAttribute(attribute, translated);
    }
  }

  function translateTree(node: Node) {
    if (node instanceof Element && node.closest("[data-no-translate]")) return;
    if (node.nodeType === Node.TEXT_NODE) {
      translateText(node);
      return;
    }
    if (node instanceof Element) translateAttributes(node);
    for (const child of node.childNodes) translateTree(child);
  }

  translateTree(document.body);
  const observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === "attributes") translateAttributes(record.target as Element);
      else if (record.type === "characterData") translateText(record.target);
      else for (const node of record.addedNodes) translateTree(node);
    }
  });
  observer.observe(document.body, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: ["aria-label", "placeholder", "title", "alt"],
  });
  return () => observer.disconnect();
}
